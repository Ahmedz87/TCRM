/** Returns a translate function. In English mode it's the identity (returns the key). */
export function adminT(lang?: string): (en: string) => string {
  const ar = lang === 'ar';
  return (en: string): string => (ar && AR[en] != null ? AR[en] : en);
}

// --- React context so ANY component can translate without prop-drilling `lang` ---
export const LangContext = createContext<string>('en');
/** Current language from context. */
export function useLang(): string { return useContext(LangContext); }
/** Translate hook: const t = useT(); <span>{t('Save')}</span> */
export function useT(): (en: string) => string { return adminT(useContext(LangContext)); }
