FIXED = "10121420010100166"   # the block after the 8-digit date


def main():
    rows = sorted(ROWS, key=lambda r: datetime.strptime(r[0], "%d/%m/%Y %H:%M"))
    print(f"{'#':>2}  {'date & time':16}  {'tail (after date+block)':24}  {'full txid':40}  trend")
    prev_full = prev_tail = None
    full_mono = tail_mono = True
    full_drops = tail_drops = 0
    for i, (dt, txid) in enumerate(rows, 1):
        full = int(txid)
        tail = txid[8 + len(FIXED):] if txid[8:8+len(FIXED)] == FIXED else txid[8:]
        tval = int(tail) if tail.isdigit() else 0
        mark = ""
        if prev_full is not None:
            if full < prev_full:
                full_mono = False; full_drops += 1
            tdir = "UP" if tval > prev_tail else ("=" if tval == prev_tail else "DOWN")
            mark = ("full+ " if full >= prev_full else "full- ") + f"tail:{tdir}"
        print(f"{i:>2}  {dt:16}  {tail:24}  {txid:40}  {mark}")
        prev_full, prev_tail = full, tval
    print()
    print(f"FULL txid increases with time? {'YES (monotonic)' if full_mono else f'NO — {full_drops} step(s) went DOWN'}")
    print(f"TAIL increases with time?       {'YES' if tail_mono else 'NO'} (tail_drops={tail_drops if not tail_mono else 0})")
    # tail monotonic check (separate, since tail resets per day)
    prev = None; td = 0
    for dt, txid in rows:
        tail = txid[8+len(FIXED):]
        tv = int(tail) if tail.isdigit() else 0
        if prev is not None and tv < prev:
            td += 1
        prev = tv
    print(f"TAIL down-steps across the whole timeline: {td} of {len(rows)-1}")


if __name__ == "__main__":
    main()
